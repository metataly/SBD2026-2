CREATE MATERIALIZED VIEW mv_vendas_por_produto
BUILD IMMEDIATE
REFRESH FAST ON DEMAND
ENABLE QUERY REWRITE
AS
SELECT 
    v.id_produto,
    COUNT(*) AS total_transacoes,
    SUM(v.quantidade) AS qtd_total_vendida,
    SUM(v.valor_total) AS faturamento_total,
    COUNT(v.valor_total) AS count_faturamento
FROM tb_vendas v
GROUP BY v.id_produto;

SELECT 
    p.nome_produto,
    p.categoria,
    mv.total_transacoes,
    mv.qtd_total_vendida,
    mv.faturamento_total
FROM mv_vendas_por_produto mv
JOIN tb_produtos p ON p.id_produto = mv.id_produto
ORDER BY mv.faturamento_total DESC;


