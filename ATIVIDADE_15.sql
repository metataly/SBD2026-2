CREATE TABLE tb_empregados (
    id_empregado   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome           VARCHAR2(100) NOT NULL,
    cargo          VARCHAR2(50) NOT NULL,
    salario        NUMBER(10,2) NOT NULL,
    status         VARCHAR2(20) DEFAULT 'ATIVO' NOT NULL,
    data_criacao   DATE DEFAULT SYSDATE
);

CREATE TABLE tb_auditoria_salarios (
    id_audit         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empregado     NUMBER NOT NULL,
    operacao         VARCHAR2(10) NOT NULL,
    salario_anterior NUMBER(10,2),
    salario_novo     NUMBER(10,2),
    usuario_db       VARCHAR2(50) DEFAULT USER,
    data_evento      TIMESTAMP DEFAULT SYSTIMESTAMP
);

