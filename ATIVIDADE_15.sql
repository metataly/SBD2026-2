CREATE TABLE tb_departamentos_trg (
    id_departamento NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_depto      VARCHAR2(60) NOT NULL UNIQUE
);

CREATE TABLE tb_funcionarios_trg (
    id_func         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_func       VARCHAR2(100) NOT NULL,
    salario         NUMBER(10,2) NOT NULL,
    id_departamento NUMBER NOT NULL REFERENCES tb_departamentos_trg(id_departamento)
);

CREATE OR REPLACE VIEW vw_func_departamento AS
SELECT 
    f.id_func,
    f.nome_func,
    f.salario,
    d.nome_depto
FROM tb_funcionarios_trg f
JOIN tb_departamentos_trg d ON f.id_departamento = d.id_departamento;

CREATE OR REPLACE TRIGGER trg_vw_func_depto_ioi
INSTEAD OF INSERT ON vw_func_departamento
FOR EACH ROW
DECLARE
    v_id_depto NUMBER;
BEGIN
    BEGIN
        SELECT id_departamento INTO v_id_depto
        FROM tb_departamentos_trg
        WHERE UPPER(nome_depto) = UPPER(TRIM(:NEW.nome_depto));
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            INSERT INTO tb_departamentos_trg (nome_depto)
            VALUES (UPPER(TRIM(:NEW.nome_depto)))
            RETURNING id_departamento INTO v_id_depto;
    END;

    INSERT INTO tb_funcionarios_trg (nome_func, salario, id_departamento)
    VALUES (:NEW.nome_func, :NEW.salario, v_id_depto);
END trg_vw_func_depto_ioi;
/

