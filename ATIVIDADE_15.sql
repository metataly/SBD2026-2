CREATE OR REPLACE TRIGGER trg_empregados_biu_valida
BEFORE INSERT OR UPDATE ON tb_empregados
FOR EACH ROW
BEGIN
    :NEW.nome  := UPPER(TRIM(:NEW.nome));
    :NEW.cargo := UPPER(TRIM(:NEW.cargo));

    IF :NEW.salario < 1412.00 THEN
        RAISE_APPLICATION_ERROR(-20001, 'Violação: O salário informado não pode ser inferior ao piso da categoria.');
    END IF;

    IF UPDATING THEN
        IF :NEW.salario < :OLD.salario THEN
            RAISE_APPLICATION_ERROR(-20002, 'Violação: Não é permitida a redução nominal do salário de um colaborador ativo.');
        END IF;
    END IF;
END trg_empregados_biu_valida;
/

CREATE OR REPLACE TRIGGER trg_empregados_auditoria
AFTER INSERT OR UPDATE OR DELETE ON tb_empregados
FOR EACH ROW
BEGIN
    IF INSERTING THEN
        INSERT INTO tb_auditoria_salarios (id_empregado, operacao, salario_anterior, salario_novo)
        VALUES (:NEW.id_empregado, 'INSERT', NULL, :NEW.salario);
    ELSIF UPDATING THEN
        IF :NEW.salario <> :OLD.salario THEN
            INSERT INTO tb_auditoria_salarios (id_empregado, operacao, salario_anterior, salario_novo)
            VALUES (:OLD.id_empregado, 'UPDATE', :OLD.salario, :NEW.salario);
        END IF;
    ELSIF DELETING THEN
        INSERT INTO tb_auditoria_salarios (id_empregado, operacao, salario_anterior, salario_novo)
        VALUES (:OLD.id_empregado, 'DELETE', :OLD.salario, NULL);
    END IF;
END trg_empregados_auditoria;
/

CREATE OR REPLACE TRIGGER trg_bloqueio_fim_semana
BEFORE DELETE ON tb_empregados
DECLARE
    v_dia_semana VARCHAR2(20);
BEGIN
    v_dia_semana := TO_CHAR(SYSDATE, 'DY', 'NLS_DATE_LANGUAGE=ENGLISH');

    IF v_dia_semana IN ('SAT', 'SUN') THEN
        RAISE_APPLICATION_ERROR(-20005, 'Operações de exclusão de dados são proibidas durante finais de semana.');
    END IF;
END trg_bloqueio_fim_semana;
