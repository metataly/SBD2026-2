CREATE OR REPLACE TRIGGER trg_empregados_mutante
AFTER INSERT OR UPDATE ON tb_empregados
FOR EACH ROW
DECLARE
    v_qtd_cargo NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_qtd_cargo
    FROM tb_empregados
    WHERE cargo = :NEW.cargo;
END trg_empregados_mutante;
