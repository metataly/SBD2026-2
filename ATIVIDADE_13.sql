CREATE OR REPLACE FUNCTION fnc_calcular_tempo_casa (
    p_data_admissao IN DATE
) RETURN NUMBER IS
BEGIN
    IF p_data_admissao IS NULL OR p_data_admissao > SYSDATE THEN
        RETURN 0;
    END IF;

    RETURN FLOOR(MONTHS_BETWEEN(SYSDATE, p_data_admissao) / 12);
EXCEPTION
    WHEN OTHERS THEN
        RETURN 0;
END fnc_calcular_tempo_casa;
/

SELECT 
    nome,
    data_admissao,
    fnc_calcular_tempo_casa(data_admissao) AS anos_completos
FROM tb_colaboradores
ORDER BY anos_completos DESC;

